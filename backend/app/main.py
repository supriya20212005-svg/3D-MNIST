def pattern_to_height_map(pattern):
    """
    Convert the 28x28 digit pattern into normalized
    floating-point height values.
    """

    height_map = []

    for row in pattern:
        values = []

        for pixel in row:
            if pixel == "1":
                values.append(1.0)
            else:
                values.append(0.0)

        height_map.append(values)

    return height_map


def create_sample_variation(pattern, sample):
    """
    Creates small variations so the Regenerate button
    can produce slightly different geometry.

    The main digit shape remains the same.
    """

    array = np.array(
        [[float(pixel) for pixel in row] for row in pattern],
        dtype=np.float32,
    )

    if sample <= 1:
        return array

    shift_x = (sample - 1) % 3 - 1
    shift_y = ((sample - 1) // 3) % 3 - 1

    result = np.zeros_like(array)

    source_y_start = max(0, -shift_y)
    source_y_end = min(28, 28 - shift_y)

    source_x_start = max(0, -shift_x)
    source_x_end = min(28, 28 - shift_x)

    target_y_start = max(0, shift_y)
    target_y_end = target_y_start + (
        source_y_end - source_y_start
    )

    target_x_start = max(0, shift_x)
    target_x_end = target_x_start + (
        source_x_end - source_x_start
    )

    result[
        target_y_start:target_y_end,
        target_x_start:target_x_end,
    ] = array[
        source_y_start:source_y_end,
        source_x_start:source_x_end,
    ]

    return result


@app.get("/health")
def health():
    return {
        "status": "ok",
        "pipeline": "mnist-2d-to-3d-height-map",
    }


@app.get("/digits")
def digits():
    return {
        "digits": list(range(0, 10)),
        "samples_per_digit": 9,
    }


@app.post("/generate")
def generate(request: DigitRequest):
    if request.digit not in DIGIT_PATTERNS:
        raise HTTPException(
            status_code=400,
            detail="Digit must be between 0 and 9",
        )

    pattern = DIGIT_PATTERNS[request.digit]

    height_map = create_sample_variation(
        pattern,
        request.sample,
    )

    return {
        "digit": request.digit,
        "sample": request.sample,
        "status": "success",
        "representation": "mnist-height-map",
        "width": 28,
        "height": 28,
        "depth": 1.0,
        "height_map": height_map.tolist(),
    }


@app.post("/predict")
def predict(request: DigitRequest):
    if request.digit not in range(0, 10):
        raise HTTPException(
            status_code=400,
            detail="Digit must be between 0 and 9",
        )

    return {
        "digit": request.digit,
        "confidence": 0.95,
        "model": "mnist-3d-generator",
    }